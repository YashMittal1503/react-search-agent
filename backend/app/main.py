"""FastAPI app: SSE chat + thread CRUD for anonymous clients.

Endpoints
    GET    /health                          liveness probe
    GET    /api/status                      which providers/keys are configured (no secrets), and the limits
    GET    /api/suggestions                 pre-loaded questions for the empty state
    GET    /api/threads                     the caller's threads
    POST   /api/threads                     create a thread
    PATCH  /api/threads/{id}                rename / pin
    DELETE /api/threads/{id}                delete with its messages
    GET    /api/threads/{id}/messages       history for re-rendering a thread
    POST   /api/chat                        run one turn; responds with a Server-Sent Events stream

There are no accounts: each browser sends a random ``X-Client-Id`` and only sees its own threads. Abuse is kept in
check by per-IP daily limits (``api/limits.py``).
"""

from __future__ import annotations

import json
import logging
import re
from contextlib import asynccontextmanager
from typing import Literal

from fastapi import FastAPI, Header, HTTPException, Request
from fastapi.middleware.cors import CORSMiddleware
from pydantic import BaseModel, Field
from sse_starlette.sse import EventSourceResponse

from .agent.runner import close_graph, init_graph, run_turn
from .api import limits
from .api.suggestions import SUGGESTIONS
from .llm import get_router
from .observability import flush_traces, setup_observability
from .settings import get_settings
from .store import db

logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)s %(name)s: %(message)s")
logger = logging.getLogger("app")


@asynccontextmanager
async def lifespan(app: FastAPI):
    """Startup: create tables and compile the agent graph with its SQLite checkpointer. Shutdown: close it."""
    await db.init_db()
    await init_graph()
    yield
    await close_graph()
    flush_traces()


app = FastAPI(title="react-search-agent", version="0.1.0", lifespan=lifespan)
setup_observability(app)
app.add_middleware(
    CORSMiddleware,
    allow_origins=[o.strip() for o in get_settings().frontend_origins.split(",") if o.strip()],
    allow_methods=["*"],
    allow_headers=["*"],
)

# Client ids are generated by the frontend (UUIDs); anything else is rejected before touching the database.
_CLIENT_RE = re.compile(r"^[A-Za-z0-9\-]{8,64}$")


def _owner(client_id: str | None) -> str:
    """Validate the ``X-Client-Id`` header and return it as the owner key (400 if missing or malformed)."""
    if not client_id or not _CLIENT_RE.match(client_id):
        raise HTTPException(400, "Missing or invalid X-Client-Id header")
    return client_id


class ChatIn(BaseModel):
    """Body of ``POST /api/chat``. Without ``thread_id`` (or with an unknown one) a new thread is created."""

    message: str = Field(min_length=1, max_length=4000)
    thread_id: str | None = None
    mode: Literal["auto", "quick", "deep"] = "auto"
    timezone: str = "UTC"
    locale: str = "en-US"


class ThreadPatch(BaseModel):
    """Body of ``PATCH /api/threads/{id}``; omitted fields are left unchanged."""

    title: str | None = Field(default=None, max_length=120)
    pinned: bool | None = None


@app.get("/health")
async def health():
    """Liveness probe for hosting platforms."""
    return {"ok": True}


@app.get("/api/status")
async def status():
    """What this backend can use right now: key counts per LLM provider, search providers, browser fetch, limits."""
    s = get_settings()
    return {
        "llm_keys": {k: v for k, v in get_router().key_counts().items() if v},
        "search": {"tavily": bool(s.tavily_api_key), "exa": bool(s.exa_api_key), "searxng": bool(s.searxng_url), "duckduckgo": True},
        "browser_fetch": s.enable_browser_fetch,
        "limits": {"chat_per_day": s.rate_limit_per_day, "deep_per_day": s.deep_rate_limit_per_day},
    }


@app.get("/api/suggestions")
async def suggestions():
    """Suggestion cards for the empty state (each card also previews its background scene)."""
    return SUGGESTIONS


@app.get("/api/threads")
async def threads(x_client_id: str | None = Header(default=None)):
    """The caller's threads, most recent first."""
    return await db.list_threads(_owner(x_client_id))


@app.post("/api/threads")
async def new_thread(x_client_id: str | None = Header(default=None)):
    """Create an empty thread for the caller."""
    return await db.create_thread(_owner(x_client_id))


@app.patch("/api/threads/{thread_id}")
async def patch_thread(thread_id: str, body: ThreadPatch, x_client_id: str | None = Header(default=None)):
    """Rename or (un)pin one of the caller's threads."""
    t = await db.update_thread(_owner(x_client_id), thread_id, title=body.title, pinned=body.pinned)
    if not t:
        raise HTTPException(404, "thread not found")
    return t


@app.delete("/api/threads/{thread_id}")
async def remove_thread(thread_id: str, x_client_id: str | None = Header(default=None)):
    """Delete one of the caller's threads and its messages."""
    if not await db.delete_thread(_owner(x_client_id), thread_id):
        raise HTTPException(404, "thread not found")
    return {"ok": True}


@app.get("/api/threads/{thread_id}/messages")
async def messages(thread_id: str, x_client_id: str | None = Header(default=None)):
    """All messages of one of the caller's threads."""
    if not await db.get_thread(_owner(x_client_id), thread_id):
        raise HTTPException(404, "thread not found")
    return await db.list_messages(thread_id)


@app.post("/api/chat")
async def chat(body: ChatIn, request: Request, x_client_id: str | None = Header(default=None)):
    """Run one chat turn and stream it to the browser as SSE.

    Event order: ``thread`` (the thread id, so a new chat can update its URL), then the agent's events
    (``route``, ``scene``, ``plan``, ``step``, ``source``, ``token``, ``widget``, ``citations``, ``followups``,
    ``title``, ``notice``), and finally ``done``. The user message is saved before the run; the assistant message
    is saved on ``done`` with all metadata needed to re-render it later.
    """
    owner = _owner(x_client_id)
    s = get_settings()
    limits.check(request, "chat", s.rate_limit_per_day)
    if body.mode == "deep":
        limits.check(request, "deep research", s.deep_rate_limit_per_day)

    thread = await db.get_thread(owner, body.thread_id) if body.thread_id else None
    if thread is None:
        thread_id = (await db.create_thread(owner))["id"]
    else:
        thread_id = thread.id
    await db.add_message(thread_id, "user", body.message)

    async def events():
        """The SSE generator: relays agent events and records what's needed to persist the answer."""
        steps: dict[int, dict] = {}          # timeline steps, merged by id (running -> done/failed)
        plan: list = []
        followups: list = []
        yield {"event": "thread", "data": json.dumps({"thread_id": thread_id})}
        async for ev in run_turn(body.message, thread_id, body.mode, body.timezone, body.locale):
            name, data = ev["event"], ev["data"]
            if name == "step":
                steps.setdefault(data["id"], {}).update(data)
            elif name == "plan":
                plan = data["todos"]
            elif name == "followups":
                followups = data["items"]
            elif name == "done":
                route = data.get("route") or {}
                # Steps still "running" when the turn ended were cut off by a time budget; store them as failed
                # so a reloaded thread doesn't show spinners forever.
                done_steps = [{**st, "status": "failed", "detail": "stopped (time budget)"} if st.get("status") == "running" else st
                              for st in steps.values()]
                meta = {**data, "steps": done_steps, "plan": plan, "follow_ups": followups}
                meta.pop("answer", None)       # the answer is the message content; don't store it twice
                await db.add_message(thread_id, "assistant", data.get("answer", ""), meta)
                await db.update_thread(owner, thread_id, title=data.get("title"), scene=route.get("scene"))
            if await request.is_disconnected():   # user closed the tab / pressed stop: stop the agent too
                logger.info("client disconnected from thread %s", thread_id)
                break
            yield {"event": name, "data": json.dumps(data, ensure_ascii=False, default=str)}

    return EventSourceResponse(events(), ping=15)   # keep-alive comments so proxies don't drop long deep runs
